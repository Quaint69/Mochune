fn main() {
    println!("cargo:rerun-if-changed=packaging/app.rc");
    println!("cargo:rerun-if-changed=ui/assets/app.ico");
    println!("cargo:rerun-if-env-changed=MOCHUNE_LLVM_RC");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        build_windows_interpolation();
        let compiler = std::env::var_os("MOCHUNE_LLVM_RC")
            .map(std::path::PathBuf::from)
            .or_else(|| {
                std::env::var_os("RUST_EXTERNAL_ROOT")
                    .map(|p| std::path::PathBuf::from(p).join("tools/bin/llvm-rc"))
            })
            .unwrap_or_else(|| "llvm-rc".into());
        let resource =
            std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap()).join("mochune-icon.res");
        let status = std::process::Command::new(compiler)
            .args(["/no-preprocess", "/FO"])
            .arg(&resource)
            .arg("packaging/app.rc")
            .status()
            .expect("Windows icon resource compiler unavailable (set MOCHUNE_LLVM_RC)");
        assert!(status.success(), "Windows icon resource compilation failed");
        println!("cargo:rustc-link-arg-bin=mochune={}", resource.display());
    }

    // Explicit contexts keep the offscreen software controls independent of
    // the native desktop window. The compiler and runtime are pinned to 1.18.1.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        || std::env::var_os("CARGO_FEATURE_NATIVE_OVERLAY_TEST").is_some()
    {
        // This build script is single-threaded, before Slint compilation starts.
        unsafe {
            std::env::set_var("SLINT_ENABLE_EXPERIMENTAL_FEATURES", "1");
        }
    }
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        || std::env::var_os("CARGO_FEATURE_NATIVE_OVERLAY_TEST").is_some()
    {
        let overlay_config = slint_build::CompilerConfiguration::new()
            .embed_resources(slint_build::EmbedResourcesKind::EmbedFiles);
        slint_build::compile_with_config("ui/native-player.slint", overlay_config)
            .expect("Native controls UI failed to compile");
        println!(
            "cargo:rustc-env=MOCHUNE_NATIVE_UI={}",
            std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap())
                .join("native-player.rs")
                .display()
        );
    }
    let config = slint_build::CompilerConfiguration::new()
        .embed_resources(slint_build::EmbedResourcesKind::EmbedFiles);
    slint_build::compile_with_config("ui/setup.slint", config)
        .expect("Slint setup UI failed to compile");
}

// Compile the existing motion shaders for Direct3D without maintaining a second
// copy of the algorithm. The small compatibility header is native HLSL.
fn build_windows_interpolation() {
    use std::{env, fs, path::PathBuf};
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let mut header = String::from("#pragma once\n");
    for name in ["motion", "refine", "seed", "warp", "preview", "consensus"] {
        let path = format!("src/video/interpolation/{name}.frag");
        println!("cargo:rerun-if-changed={path}");
        let source = fs::read_to_string(&path).unwrap();
        let body = source
            .lines()
            .filter(|line| {
                !line.starts_with("uniform ")
                    && !line.starts_with("in vec2 uv;")
                    && !line.starts_with("out vec4 result;")
            })
            .collect::<Vec<_>>()
            .join("\n")
            .replace("void main()", "void source_main()")
            .replace("vec3 patch_a[9];", "static vec3 patch_a[9];")
            .replace("vec3 patch_b[9];", "static vec3 patch_b[9];")
            .replace("for(", "[loop] for(");
        header.push_str(&format!(
            "static const char *shader_{name}=R\"MOCHUNE({body})MOCHUNE\";\n"
        ));
    }
    fs::write(out.join("mochune_interpolation_shaders.h"), header).unwrap();
    // Bytecode is generated by the Windows shader compiler from these same
    // sources. The native loader checks the full HLSL fingerprint; edited shader
    // sources automatically fall back to in-memory compilation, never stale code.
    let cache_dir = PathBuf::from("assets/interpolation/windows");
    let manifest = fs::read_to_string(cache_dir.join("manifest.txt")).unwrap_or_default();
    let mut cache = String::from(
        "#pragma once\nstruct CachedShader { uint64_t hash;const unsigned char *data;size_t size; };\n",
    );
    let mut entries = Vec::new();
    for line in manifest.lines() {
        let fields = line.split_whitespace().collect::<Vec<_>>();
        if fields.len() != 2 {
            continue;
        }
        let name = fields[0];
        if !["motion", "refine", "seed", "warp", "preview", "consensus"].contains(&name) {
            continue;
        }
        let hash = u64::from_str_radix(fields[1], 16).expect("Invalid shader fingerprint");
        let file = cache_dir.join(format!("{name}.dxbc"));
        let bytes = fs::read(&file).expect("Shader bytecode missing");
        assert!(
            bytes.starts_with(b"DXBC") && bytes.len() < 1_048_576,
            "Invalid cached shader"
        );
        cache.push_str(&format!("static const unsigned char cached_{name}[]={{"));
        for byte in &bytes {
            cache.push_str(&format!("{byte},"));
        }
        cache.push_str("};\n");
        entries.push(format!("{{{hash}ull,cached_{name},sizeof(cached_{name})}}"));
        println!("cargo:rerun-if-changed={}", file.display());
    }
    cache.push_str(&format!(
        "static const std::array<CachedShader,{}> cached_shaders={{{{{}}}}};\n",
        entries.len(),
        entries.join(",")
    ));
    fs::write(out.join("mochune_interpolation_cache.h"), cache).unwrap();
    println!("cargo:rerun-if-changed=assets/interpolation/windows/manifest.txt");
    let root = env::var_os("GSTREAMER_1_0_ROOT_MSVC_X86_64")
        .map(PathBuf::from)
        .or_else(|| {
            env::var_os("RUST_EXTERNAL_ROOT")
                .map(|r| PathBuf::from(r).join("windows/gstreamer/msvc_x86_64"))
        })
        .expect("Windows GStreamer SDK path unavailable");
    cc::Build::new()
        .define("GST_USE_UNSTABLE_API", None)
        .cpp(true)
        .file("src/video/windows_interpolation.cpp")
        .include(&out)
        .include(root.join("include/gstreamer-1.0"))
        .include(root.join("include/glib-2.0"))
        .include(root.join("lib/glib-2.0/include"))
        .flag_if_supported("/std:c++17")
        .flag_if_supported("/EHsc")
        .opt_level(2)
        .debug(false)
        .compile("mochune_interpolation");
    for lib in ["d3d12", "dxgi", "d3dcompiler", "gstd3d12-1.0"] {
        println!("cargo:rustc-link-lib={lib}");
    }
    // Music/desktop startup must not map interpolation's native graphics stack.
    println!("cargo:rustc-link-lib=delayimp");
    for dll in ["gstd3d12-1.0-0.dll", "d3d12.dll", "d3dcompiler_47.dll"] {
        println!("cargo:rustc-link-arg=/DELAYLOAD:{dll}");
    }
    println!("cargo:rerun-if-changed=src/video/windows_interpolation.cpp");
}
